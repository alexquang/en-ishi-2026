<?php
/**
 * Receipt PDF renderer.
 *
 * Generates a server-side PDF receipt for a single transaction using the
 * Dompdf library vendored at `vendor/dompdf/dompdf/`. Permission is owner-
 * only — Admin staff have a separate refund flow on the admin transactions
 * page.
 *
 * Usage:
 *   Receipt_PDF_Service::stream( $txn_id, $user_id );
 *
 * Streams the PDF directly to the browser with download headers and exits.
 *
 * @package Learnomy
 */

namespace Learnomy\Services;

defined( 'ABSPATH' ) || exit;

use Learnomy\Vendor\Dompdf\Dompdf;
use Learnomy\Vendor\Dompdf\Options;
use Learnomy\Models\Course;
use Learnomy\Models\MembershipPlan;
use Learnomy\Models\Transaction;

class Receipt_PDF_Service {

	/**
	 * Stream a receipt PDF for the given transaction to the requesting user.
	 *
	 * Exits the request. If the user is not the owner, or the txn doesn't
	 * exist, sends a 404 and exits.
	 */
	public static function stream( int $txn_id, int $user_id ): void {
		$txn = Transaction::find( $txn_id );

		if ( ! $txn || (int) $txn->user_id !== $user_id ) {
			status_header( 404 );
			nocache_headers();
			exit;
		}

		$html = self::render_html( $txn );

		// Render with the committed, scoped dompdf in libs/ (no composer install).
		$autoload = LEARNOMY_DIR . 'libs/autoload.php';
		if ( file_exists( $autoload ) ) {
			require_once $autoload;
		}

		if ( ! class_exists( '\\Learnomy\\Vendor\\Dompdf\\Dompdf' ) ) {
			// Library missing — fall back to HTML download so the customer
			// still gets *something* they can print. This should never
			// happen on a properly-built release.
			header( 'Content-Type: text/html; charset=utf-8' );
			echo $html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- composed in render_html().
			exit;
		}

		$options = new Options();
		$options->set( 'isRemoteEnabled', false );
		$options->set( 'defaultFont', 'sans-serif' );

		$dompdf = new Dompdf( $options );
		$dompdf->loadHtml( $html, 'UTF-8' );
		$dompdf->setPaper( 'A4', 'portrait' );
		$dompdf->render();

		$filename = sprintf( 'learnomy-receipt-%d.pdf', $txn_id );

		header( 'Content-Type: application/pdf' );
		header( 'Content-Disposition: attachment; filename="' . $filename . '"' );
		header( 'Cache-Control: private, no-store' );

		echo $dompdf->output(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- binary PDF.
		exit;
	}

	/**
	 * Render the receipt HTML used by Dompdf. Kept inline so we ship a
	 * single deterministic template with no theme override surface.
	 */
	private static function render_html( object $txn ): string {
		$settings = get_option( 'learnomy_settings', array() );
		// Fall back to the site name when business_name is unset OR empty — the
		// `??` alone kept an empty-string setting, rendering "Generated by ."
		$business = trim( (string) ( $settings['business_name'] ?? '' ) );
		if ( '' === $business ) {
			$business = (string) get_bloginfo( 'name' );
		}
		$refund_pol = (string) ( $settings['refund_policy_text'] ?? '' );
		$currency   = strtoupper( (string) ( $txn->currency ?? 'USD' ) );
		$user       = get_userdata( (int) $txn->user_id );
		$user_name  = $user ? trim( $user->first_name . ' ' . $user->last_name ) : '';
		if ( '' === $user_name && $user ) {
			$user_name = $user->display_name;
		}
		$user_email = $user ? $user->user_email : '';
		$date       = mysql2date( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ), (string) $txn->created_at );

		$item_title = __( 'Purchase', 'learnomy' );
		if ( ! empty( $txn->course_id ) ) {
			$course = Course::find( (int) $txn->course_id );
			if ( $course ) {
				$item_title = (string) $course->title;
			}
		} elseif ( ! empty( $txn->plan_id ) ) {
			$plan = MembershipPlan::find( (int) $txn->plan_id );
			if ( $plan ) {
				$item_title = (string) $plan->title;
			}
		}

		$amount   = number_format( (float) $txn->amount, 2 );
		$provider = ucfirst( (string) ( $txn->payment_provider ?? '' ) );
		$ptid     = (string) ( $txn->provider_transaction_id ?? '' );

		// SELL-02: a simulated Test-gateway order is recorded at $0. The
		// receipt must say so explicitly — "Total paid 0.00" alone reads as a
		// billing error once the site has left test mode.
		$is_test_order = null !== Transaction::simulated_listed_price( $txn );

		ob_start();
		?>
		<!DOCTYPE html>
		<html lang="en">
		<head>
		<meta charset="UTF-8">
		<style>
			body { font-family: sans-serif; color: #222; font-size: 12px; line-height: 1.5; }
			.header { border-bottom: 2px solid #222; padding-bottom: 12px; margin-bottom: 24px; }
			.header h1 { margin: 0; font-size: 22px; }
			.header .biz { color: #666; margin-top: 4px; }
			.meta-grid { display: table; width: 100%; margin-bottom: 28px; }
			.meta-grid > div { display: table-row; }
			.meta-grid dt { display: table-cell; width: 140px; color: #888; padding: 4px 0; }
			.meta-grid dd { display: table-cell; padding: 4px 0; margin: 0; }
			table.items { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
			table.items th, table.items td { padding: 10px 8px; text-align: left; border-bottom: 1px solid #eee; }
			table.items th { background: #fafafa; font-weight: 600; }
			.totals { text-align: right; font-size: 14px; }
			.totals .label { color: #666; margin-right: 12px; }
			.totals .value { font-weight: 700; font-size: 18px; }
			.footer { margin-top: 36px; padding-top: 16px; border-top: 1px solid #eee; color: #666; font-size: 11px; }
			.refund-policy { margin-top: 20px; padding: 12px; background: #fafafa; border-left: 3px solid #ddd; font-size: 11px; }
		</style>
		</head>
		<body>
			<div class="header">
				<h1><?php esc_html_e( 'Receipt', 'learnomy' ); ?></h1>
				<div class="biz"><?php echo esc_html( $business ); ?></div>
			</div>

			<div class="meta-grid">
				<div><dt><?php esc_html_e( 'Order ID', 'learnomy' ); ?></dt><dd>#<?php echo (int) $txn->id; ?></dd></div>
				<div><dt><?php esc_html_e( 'Date', 'learnomy' ); ?></dt><dd><?php echo esc_html( $date ); ?></dd></div>
				<div><dt><?php esc_html_e( 'Customer', 'learnomy' ); ?></dt><dd><?php echo esc_html( $user_name ); ?></dd></div>
				<div><dt><?php esc_html_e( 'Email', 'learnomy' ); ?></dt><dd><?php echo esc_html( $user_email ); ?></dd></div>
				<div><dt><?php esc_html_e( 'Payment', 'learnomy' ); ?></dt><dd><?php echo esc_html( $provider ); ?></dd></div>
				<?php if ( $ptid ) : ?>
				<div><dt><?php esc_html_e( 'Reference', 'learnomy' ); ?></dt><dd><?php echo esc_html( $ptid ); ?></dd></div>
				<?php endif; ?>
			</div>

			<table class="items">
				<thead>
					<tr>
						<th><?php esc_html_e( 'Item', 'learnomy' ); ?></th>
						<th style="text-align: right;"><?php esc_html_e( 'Amount', 'learnomy' ); ?></th>
					</tr>
				</thead>
				<tbody>
					<tr>
						<td><?php echo esc_html( $item_title ); ?></td>
						<td style="text-align: right;"><?php echo esc_html( $currency . ' ' . $amount ); ?></td>
					</tr>
				</tbody>
			</table>

			<div class="totals">
				<span class="label"><?php esc_html_e( 'Total paid', 'learnomy' ); ?></span>
				<span class="value"><?php echo esc_html( $currency . ' ' . $amount ); ?></span>
			</div>

			<?php if ( $is_test_order ) : ?>
				<div class="refund-policy">
					<strong><?php esc_html_e( 'Test order', 'learnomy' ); ?></strong><br>
					<?php esc_html_e( 'This order was placed in test payment mode. No real payment was taken.', 'learnomy' ); ?>
				</div>
			<?php endif; ?>

			<?php if ( $refund_pol ) : ?>
				<div class="refund-policy">
					<strong><?php esc_html_e( 'Refund policy', 'learnomy' ); ?></strong><br>
					<?php echo wp_kses_post( $refund_pol ); ?>
				</div>
			<?php endif; ?>

			<div class="footer">
				<?php
				printf(
					/* translators: %s: site name */
					esc_html__( 'Generated by %s. Questions? Reply to your purchase confirmation email.', 'learnomy' ),
					esc_html( $business )
				);
				?>
			</div>
		</body>
		</html>
		<?php
		return (string) ob_get_clean();
	}
}
